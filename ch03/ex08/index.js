console.log("true to Num:",Number(true)); //true to Num: 1
console.log("1234 to Num:",Number(1234)); //1234 to Num: 1234
console.log("text to Num:",Number("text")); //text to Num: NaN

console.log("1234 to Bool:",Boolean(1234)); //1234 to Bool: true
console.log("0 to Bool:",Boolean(0)); //0 to Bool: false

console.log("true to string:",String(true)); //true to string: true
console.log("1234 to String:",String(1234)); //1234 to String: 1234

console.log(parseInt("12,742 km：地球の直径")); //12
console.log(parseFloat("1.618：黄金比")); //1.618